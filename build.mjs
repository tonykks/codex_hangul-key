// The browser bundle uses a classic script so index.html also works via file://.
// Source modules remain available for direct Node tests. No packages are needed.
import {readFile,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
export async function browserBundle(){
 const files=['practice-data.js','core.js','cloud-model.js','translations.js','firebase-config.js','auth.js','cloud.js','app.js'];
 const sources=await Promise.all(files.map(async file=>{
  const source=await readFile(new URL(file,import.meta.url),'utf8');
  const script=source.replace(/^import .* from ['"].*['"];\r?\n/gm,'').replace(/^export (?=(?:const|function)\b)/gm,'');
  if(/^\s*(import|export)\s/m.test(script))throw Error(`Unsupported module syntax in ${file}`);
  return `// ${file}\n${script}`;
 }));
 return '// Generated by node build.mjs. Edit source modules, then rebuild.\n(()=>{\n"use strict";\n'+sources.join('\n')+'\n})();\n';
}
if(process.argv[1] && pathToFileURL(process.argv[1]).href===import.meta.url){
 await writeFile(new URL('app.bundle.js',import.meta.url),await browserBundle(),'utf8');
 console.log('Built app.bundle.js');
}
